/* M1b: action planner purity and M1a live combat outcomes golden comparisons. */
'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const actions=require('../core/actions.js');
const ROOT=path.resolve(__dirname,'..');
const golden=JSON.parse(fs.readFileSync(path.join(__dirname,'fixtures/actions-golden-m1a.json'),'utf8'));

function runtime(seed=555){
 const saved=new Map(),nodes=new Map(),m=Object.create(Math);
 let state=seed>>>0;
 m.random=()=>((state=(Math.imul(state,1664525)+1013904223)>>>0)/4294967296);
 const el=()=>({innerHTML:'',className:'',textContent:'',remove(){},click(){},classList:{add(){},remove(){},toggle(){}}});
 const document={
  documentElement:{dataset:{phaserPreview:'true'}},
  getElementById(id){if(!nodes.has(id))nodes.set(id,el());return nodes.get(id);},
  querySelector(sel){return this.getElementById(sel);},
  createElement:el,addEventListener(){},body:{append(){}}
 };
 const ctx=vm.createContext({document,Math:m,navigator:{},console:{warn(){},log(){},error(){}},
  localStorage:{getItem:k=>saved.get(k)||null,setItem:(k,v)=>saved.set(k,v),removeItem:k=>saved.delete(k)},
  setTimeout(){},clearTimeout(){},Blob:class{},URL:class{}});
 for(const file of ['data.js','core/combat.js','core/actions.js','core/effects.js','app.js']){
  vm.runInContext(fs.readFileSync(path.join(ROOT,file),'utf8'),ctx,{filename:file});
 }
 return {exec:code=>vm.runInContext(code,ctx),saved};
}
function copy(value){return JSON.parse(JSON.stringify(value));}
function setup(run,sc){
 const {exec}=run;
 exec("S=fresh('story');screen='game';S.day="+sc.day+";S.flags['council_'+Math.floor((S.day-1)/6)]='povo';beginBattle();S.battle.active="+JSON.stringify(sc.actor));
 if(sc.setup==='injured')exec('S.heroes.brunna.hp=23');
 else if(sc.setup==='outmp')exec('S.heroes.serena.mp=1');
 else if(sc.setup==='fallen')exec('S.heroes.brunna.hp=0');
 else if(sc.setup==='poison')exec('S.heroes.brunna.status.poison=3');
}
function digest(exec){return copy(exec("JSON.parse(JSON.stringify({day:S.day,mode:S.mode,heroes:S.battle.party.map(id=>({id,hp:S.heroes[id].hp,mp:S.heroes[id].mp,barrier:S.heroes[id].barrier,status:S.heroes[id].status,injured:S.heroes[id].injured})),foes:S.battle.foes,active:S.battle.active,round:S.battle.round,logs:S.battle.logs.slice(0,12),inventory:S.inventory,history:S.history,victories:S.victories}))"));}
test('golden actions were captured before validation extraction, not generated by the new planner',()=>{
 assert.equal(golden.source_commit,'9ac70fda7ae3f92d6484e7b94214768b33228459');
 assert.equal(golden.seed,555);
 assert.equal(golden.fixtures.length,14);
});
for(const entry of golden.fixtures){
 test('original M1a outcome: '+entry.scenario.kind+' '+entry.scenario.key+' day '+entry.scenario.day+' '+(entry.scenario.setup||''),()=>{
  const run=runtime(golden.seed),sc=entry.scenario;
  setup(run,sc);
  run.exec(sc.kind==='skill'?"doSkill("+JSON.stringify(sc.key)+","+JSON.stringify(sc.target)+")":
    "useCombatItem("+JSON.stringify(sc.key)+","+JSON.stringify(sc.target)+")");
  assert.deepEqual(digest(run.exec),entry.expected);
 });
}
test('planning never mutates state, while respecting dead allies, living enemies and self',()=>{
 const run=runtime(18);setup(run,{day:1,actor:'serena'});
 const state=copy(run.exec('S')),skills=copy(run.exec('SKILLS')),classes=copy(run.exec('CLASSES'));
 const original=copy(state);
 assert.deepEqual(actions.selectableTargets(state,'enemy'),state.battle.foes.filter(e=>e.hp>0).map(e=>e.uid));
 assert.deepEqual(actions.selectableTargets(state,'self'),['serena']);
 assert.equal(actions.planSkill(state,'heal','brunna',skills,classes).ok,true);
 assert.equal(actions.planSkill(state,'heal','serena',skills,classes).ok,true);
 assert.equal(actions.planSkill(state,'heal','e0',skills,classes).reason,'Selecione um aliado vivo.');
 assert.equal(actions.planSkill(state,'attack','nobody',skills,classes).reason,'Selecione um inimigo válido.');
 state.heroes.brunna.hp=0;
 assert.deepEqual(actions.selectableTargets(state,'fallen'),['brunna']);
 assert.equal(actions.planItem(state,'phoenix','brunna').ok,true);
 assert.equal(actions.planItem(state,'tonic','brunna').reason,'Use a Cinza da Chama num aliado caído.');
 state.heroes.brunna.hp=original.heroes.brunna.hp;
 assert.deepEqual(state,original);
});
test('insufficient mana/unlearned spell/invalid inventory do not change state',()=>{
 const run=runtime(19);setup(run,{day:1,actor:'eirik'});
 const state=copy(run.exec('S')),skills=copy(run.exec('SKILLS')),classes=copy(run.exec('CLASSES')),before=copy(state);
 assert.equal(actions.planSkill(state,'meteor','e0',skills,classes).reason,'Técnica ainda não aprendida.');
 state.heroes.eirik.mp=0;
 assert.equal(actions.planSkill(state,'arcaneBolt','e0',skills,classes).reason,'Mana insuficiente.');
 state.heroes.eirik.mp=before.heroes.eirik.mp;
 state.inventory.tonic=0;
 assert.equal(actions.planItem(state,'tonic','brunna').reason,'Item indisponível.');
 state.inventory.tonic=before.inventory.tonic;
 assert.deepEqual(state,before);
});
test('all-enemy and all-ally selection returns all valid combatants without sorting or mutation',()=>{
 const run=runtime(21);setup(run,{day:6,actor:'eirik'});
 const state=copy(run.exec('S')),before=copy(state);
 assert.deepEqual(actions.selectableTargets(state,'allEnemies'),state.battle.foes.map(e=>e.uid));
 assert.deepEqual(actions.selectableTargets(state,'allAllies'),state.battle.party);
 assert.deepEqual(state,before);
});
